-- 시간대
------------------------------------------------------------------------
function ns.TimeOfDay()
	local h
	if GetGameTime then
		local ok, hour = pcall(GetGameTime)
		if ok and type(hour) == "number" then h = hour end
	end
	h = h or tonumber(date("%H")) or 12
	if h >= 5 and h < 8 then return "새벽녘" end
	if h >= 8 and h < 12 then return "아침" end
	if h >= 12 and h < 16 then return "한낮" end
	if h >= 16 and h < 19 then return "해 질 녘" end
	if h >= 19 and h < 22 then return "저녁" end
	return "깊은 밤"
end

-- 종족 첫 만남 문장을 고른다
function N.FirstEncounter(tribeId, def)
	local list = N.first[tribeId]
	if not list and def and def.dynamic then list = N.first.beast end
	return ns.Pick(list or N.firstDefault)
end
