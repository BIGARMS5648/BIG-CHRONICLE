local dynCache = {}

-- 종족 정의를 돌려준다. "beast:늑대" 같은 동적 야수 계통도 처리한다.
function ns.GetTribe(id)
	if not id then return nil end
	local t = ns.TRIBE_BY_ID[id]
	if t then return t end
	t = dynCache[id]
	if t then return t end
	local fam = id:match("^beast:(.+)$")
	if not fam then return nil end
	local lore = {}
	for i, tpl in ipairs(ns.BEAST_FAMILY_LORE) do
		lore[i] = (tpl:gsub("{family(:?[^}]*)}", function(spec)
			spec = spec:gsub("^:", "")
			if spec ~= "" then return ns.Josa(fam, spec) end
			return fam
		end))
	end
	t = {
		id = id, name = fam, en = fam, family = fam, dynamic = true,
		icon = FAMILY_ICON[fam] or (I .. "Ability_Hunter_BeastTaming"),
		types = { beast = true },
		hint = "야생의 " .. fam .. " 무리가 어딘가에 있다.",
		habitats = {},
		lore = lore,
	}
	dynCache[id] = t
	return t
end
